#!/usr/bin/env python3
"""One-command NEAR testnet setup for RedactGate audit anchoring. Free, no wallet app.

    python scripts/near_setup.py                       # new rg-xxxxxx.testnet via faucet
    python scripts/near_setup.py --account me.testnet --key-env NEAR_OWNER_PRIVATE_KEY

What it does:
  1. (no --account) creates a fresh ``*.testnet`` account through the public testnet
     faucet helper; the faucet funds it with test NEAR;
  2. creates ``anchor.<account>``, funds it, deploys contracts/audit-anchor/res/audit_anchor.wasm
     and calls ``new(owner=<account>)`` — one atomic transaction;
  3. adds a *function-call* key to <account> that may only call ``anchor`` on the contract
     (no transfers) — this is the key the gateway holds;
  4. writes ``.env.near`` (0600) with NEAR_CONTRACT_ID / NEAR_SIGNER_ID / NEAR_PRIVATE_KEY.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import secrets
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.anchor import near  # noqa: E402

FAUCET = "https://helper.testnet.near.org/account"
NEAR = 10**24


async def wait_account(client: near.NearClient, account: str, tries: int = 30) -> None:
    for _ in range(tries):
        try:
            await client._rpc("query", {"request_type": "view_account", "finality": "final",
                                        "account_id": account})
            return
        except near.NearRpcError:
            await asyncio.sleep(2)
    raise SystemExit(f"account {account} did not appear on testnet")


async def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--account", help="existing testnet account (owner); default: create one")
    ap.add_argument("--key-env", default="NEAR_OWNER_PRIVATE_KEY",
                    help="env var holding the owner's full-access ed25519:... key")
    ap.add_argument("--sub", default="anchor", help="contract sub-account prefix")
    ap.add_argument("--fund", type=float, default=2.5, help="test NEAR sent to the contract")
    ap.add_argument("--wasm", default=str(ROOT / "contracts/audit-anchor/res/audit_anchor.wasm"))
    ap.add_argument("--env-out", default=str(ROOT / ".env.near"))
    args = ap.parse_args()

    client = near.NearClient(network="testnet")
    if args.account:
        owner = args.account
        owner_key = near.KeyPair.from_string(os.environ[args.key_env])
    else:
        owner = f"rg-{secrets.token_hex(3)}.testnet"
        owner_key = near.KeyPair.generate()
        async with httpx.AsyncClient(timeout=60) as http:
            r = await http.post(FAUCET, json={"newAccountId": owner,
                                              "newAccountPublicKey": owner_key.public_key_str})
            r.raise_for_status()
        await wait_account(client, owner)
        print(f"created {owner} via testnet faucet")

    contract = f"{args.sub}.{owner}"
    code = Path(args.wasm).read_bytes()
    res = await client.send(
        signer_id=owner, key=owner_key, receiver_id=contract,
        actions=[
            near.create_account(),
            near.transfer(int(args.fund * NEAR)),
            near.add_full_access_key(owner_key.public),
            near.deploy_contract(code),
            near.function_call("new", {"owner": owner}, gas=30 * near.TGAS),
        ],
    )
    print(f"deployed {contract}: {client.explorer_tx(res['_tx_hash'])}")

    gw_key = near.KeyPair.generate()
    res = await client.send(
        signer_id=owner, key=owner_key, receiver_id=owner,
        actions=[near.add_function_call_key(gw_key.public, contract, ["anchor"],
                                            allowance=NEAR // 4)],
    )
    print(f"added anchor-only key {gw_key.public_key_str}: {client.explorer_tx(res['_tx_hash'])}")

    out = Path(args.env_out)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# generated by scripts/near_setup.py — testnet only\n")
        f.write("NEAR_ANCHOR_ENABLED=true\nNEAR_NETWORK=testnet\n")
        f.write(f"NEAR_CONTRACT_ID={contract}\nNEAR_SIGNER_ID={owner}\n")
        f.write(f"NEAR_PRIVATE_KEY={gw_key.secret_key_str}\n")
        if not args.account:
            f.write(f"NEAR_OWNER_PRIVATE_KEY={owner_key.secret_key_str}\n")
    print(f"wrote {out} (0600)")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
